def build(b):
    for level in range(1, 6):
        for i, (word, wrong) in enumerate(SPELL[level]):
            note = SPELL_NOTES.get(word, '')
            b.mc(M, level, SPELL_PROMPTS[i % len(SPELL_PROMPTS)], word, wrong,
                 (f"The correct spelling is '{word}'. {note}").strip())
        for j, (a, odd) in enumerate(LETTER_SETS[level]):
            n = 4 if level <= 2 else (5 if level <= 4 else 6)
            pos = (j * 2 + level) % n
            seq = [a] * n
            seq[pos] = odd
            opts = ORDINALS[:n]
            correct = ORDINALS[pos]
            wrong = [o for o in opts if o != correct][:3]
            b.mc(M, level, f"Which one is different: {', '.join(seq)}?", correct, wrong,
                 f"The {correct} one is '{odd}'. The others are '{a}'.")
        for word, wrong in FIND_SAME[level]:
            b.mc(M, level, f"Find the word '{word}'", word, wrong, f"Look carefully at every letter: {'-'.join(word)}.")
        for k, (word, wrong) in enumerate(FIND_SAME[level][:5]):
            n = 4
            pos = (k + level) % n
            seq = [word] * n
            seq[pos] = wrong[0]
            correct = ORDINALS[pos]
            b.mc(M, level, f"Which word is different: {', '.join(seq)}?", correct,
                 [o for o in ORDINALS[:n] if o != correct], f"The {correct} word is '{wrong[0]}', not '{word}'.")
        for items in ALPHA[level]:
            kind = "letters" if len(items[0]) == 1 else "words"
            b.order(M, level, f"Put the {kind} in alphabetical order", items, f"Alphabetical order: {', '.join(items)}.")
